		GPIO_InitStruct.Mode = GPIO_MODE_AF_OD;
		GPIO_InitStruct.Pull = GPIO_PULLUP;
		GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
		GPIO_InitStruct.Alternate = GPIO_AF7_USART2;
		HAL_GPIO_Init(GPIOA, &GPIO_InitStruct);

		/* PA3 RX: Open-drain with pull-up for shared PDN_UART bus.
		 * PA3 connects directly to PDN_UART (no series resistor).
		 * Push-pull AF mode causes the output stage to pull PDN_UART
		 * toward GND (~1.15V idle), corrupting the UART idle-high state.
		 * Open-drain ensures PA3 is high-impedance when not actively
		 * driven LOW, so only the TMC2209 internal pull-up (and any
		 * external pull-up) defines the idle voltage. */
		GPIO_InitStruct.Pin = GPIO_PIN_3;
		GPIO_InitStruct.Mode = GPIO_MODE_AF_OD;
		GPIO_InitStruct.Pull = GPIO_PULLUP;
