/* Exported functions --------------------------------------------------------*/

bool SensorControl_Init(void) {
	memset(&sensor_ctrl, 0, sizeof(sensor_ctrl));
	sensor_ctrl.current_state = SENSOR_STATE_DISABLED;
	sensor_ctrl.initialized = true;
	sensor_ctrl.temp_initialized = false;
	sensor_ctrl.ph_initialized = false;
	sensor_ctrl.last_control_word = 0;
	sensor_ctrl.last_status_word = 0;
	sensor_ctrl.last_tpdo_mv = 0;
	sensor_ctrl.last_tpdo_temp = 0;
	sensor_ctrl.last_tpdo_status = 0;

	/* Initialize DS18B20 temperature sensor on DQ pin (PB0) */
	if (Temp_Init(DQ_GPIO_Port, DQ_Pin) == HAL_OK) {
		sensor_ctrl.temp_initialized = true;
		DBG_PRINT(SENSOR, "Init: DS18B20 OK");
	} else {
		DBG_ERROR(SENSOR, "Init: DS18B20 FAILED (no presence)");
	}

	/* Initialize MCP3221 pH sensor on I2C1 */
	if (pH_Init(&hi2c1) == HAL_OK) {
		sensor_ctrl.ph_initialized = true;
		DBG_PRINT(SENSOR, "Init: MCP3221 pH OK");
	} else {
		DBG_ERROR(SENSOR, "Init: MCP3221 pH FAILED (not responding)");
	}

	/* Initialize tri-LED PWM control (starts TIM2/TIM3/TIM4 PWM outputs).
	 * This enables both the MCO stack's CiA 303 LED patterns (green/red)
	 * and the application-level LED control via OD 0x2000. */
	if (!LEDControl_Init(&htim2, TIM_CHANNEL_1, &htim3, TIM_CHANNEL_2, &htim4,
			TIM_CHANNEL_1)) {
		DBG_ERROR(SENSOR, "Init: LEDControl FAILED");
	} else {
		DBG_PRINT(SENSOR, "Init: LEDControl OK");
	}

	DBG_PRINT(SENSOR, "SensorControl_Init complete (temp=%s, pH=%s)",
			sensor_ctrl.temp_initialized ? "OK" : "FAIL",
			sensor_ctrl.ph_initialized ? "OK" : "FAIL");
	return true;
}

void SensorControl_Process(void) {
	if (!sensor_ctrl.initialized) {
		return;
	}

	/* ── Always tick sensor drivers (they need processing regardless) ── */

	/* Temperature sensor: report raw °C×10 (MIK owns any per-probe trim) */
	if (sensor_ctrl.temp_initialized) {
		Temp_Process();
	}

	/* Electrode ADC: acquire raw millivolts (MIK owns pH/Nernst/cal) */
	if (sensor_ctrl.ph_initialized) {
		pH_Process();
	}

	/* ── NMT gate: if not OPERATIONAL, force DISABLED ──────────────── */
	if (MY_NMT_STATE != NMTSTATE_OP) {
		if (sensor_ctrl.current_state != SENSOR_STATE_DISABLED) {
			DBG_STATE(SENSOR, "NMT not OP (0x%02X) -> DISABLED", MY_NMT_STATE);
			sensor_ctrl.current_state = SENSOR_STATE_DISABLED;
		}
		/* Still update process image so SDO reads reflect sensor data */
		SensorControl_UpdateProcessImage();
		return;
	}

	/* ── Process ControlWord (rising-edge detection) ───────────────── */
	SensorControl_ProcessControlWord(ProcImg_GetControlWord());

	/* ── CiA 404 State Machine ─────────────────────────────────────── */
	switch (sensor_ctrl.current_state) {

	case SENSOR_STATE_DISABLED:
		/* Transition to WARMING_UP when NMT is Operational */
		sensor_ctrl.warmup_start_ms = HAL_GetTick();
		sensor_ctrl.current_state = SENSOR_STATE_WARMING_UP;
		DBG_STATE(SENSOR, "DISABLED -> WARMING_UP (2s warmup)");
		break;

	case SENSOR_STATE_WARMING_UP: {
		uint32_t elapsed = HAL_GetTick() - sensor_ctrl.warmup_start_ms;
		if (elapsed >= WARMUP_TIME_MS) {
			/* Check if at least one sensor is ready */
			bool temp_ready = sensor_ctrl.temp_initialized
					&& Temp_GetState() == TEMP_STATE_READY;
			bool ph_ready = sensor_ctrl.ph_initialized
					&& pH_GetState() == PH_STATE_READY;

			if (temp_ready || ph_ready) {
				sensor_ctrl.current_state = SENSOR_STATE_RUNNING;
				DBG_STATE(SENSOR, "WARMING_UP -> RUNNING (temp=%s pH=%s)",
						temp_ready ? "ready" : "wait",
						ph_ready ? "ready" : "wait");
			} else {
				sensor_ctrl.current_state = SENSOR_STATE_FAULT;
				DBG_ERROR(SENSOR,
						"WARMING_UP -> FAULT (no sensors ready after warmup)");
			}
		}
		break;
	}

	case SENSOR_STATE_RUNNING:
		/* Delta-threshold TPDO triggering */
		SensorControl_CheckDeltaTrigger();

		/* Check for dual sensor failure → FAULT */
		{
			bool temp_error = sensor_ctrl.temp_initialized
					&& Temp_GetState() == TEMP_STATE_ERROR;
			bool ph_error = sensor_ctrl.ph_initialized
					&& pH_GetState() == PH_STATE_ERROR;

			if (temp_error && ph_error) {
				sensor_ctrl.current_state = SENSOR_STATE_FAULT;
				DBG_ERROR(SENSOR, "RUNNING -> FAULT (both sensors in error)");
			}
			/* Single sensor failure: log but don't fault */
		}
		break;

	case SENSOR_STATE_FAULT:
		/* Wait for ControlWord fault reset (handled in ProcessControlWord) */
		break;
	}

	/* ── Update process image with latest readings + StatusWord ─────── */
	SensorControl_UpdateProcessImage();

	/* ── Process application-level LED control (reads mode from OD 0x2000) ── */
	LEDControl_Process();
}

bool SensorControl_IsOperational(void) {
	return sensor_ctrl.current_state == SENSOR_STATE_RUNNING;
}

void SensorControl_EmergencyStop(void) {
	if (!sensor_ctrl.initialized) {
		return;
	}
	sensor_ctrl.current_state = SENSOR_STATE_FAULT;
	DBG_ERROR(SENSOR, "EmergencyStop called");
}

void SensorControl_Reset(void) {
	if (!sensor_ctrl.initialized) {
		return;
	}
	sensor_ctrl.current_state = SENSOR_STATE_DISABLED;
	sensor_ctrl.last_control_word = 0;
	sensor_ctrl.last_tpdo_mv = 0;
	sensor_ctrl.last_tpdo_temp = 0;
	sensor_ctrl.last_tpdo_status = 0;
	sensor_ctrl.last_status_word = 0;

	/* Clear sensor errors so they can retry */
	if (sensor_ctrl.temp_initialized) {
		Temp_ClearError();
	}
	if (sensor_ctrl.ph_initialized) {
		pH_ClearError();
	}

	DBG_STATE(SENSOR, "SensorControl_Reset: state -> DISABLED");
}

void SensorControl_RegisterMCOEvents(void) {
	MCO_Events_Register(SensorControl_HandleMCOEvent);
	DBG_PRINT(SENSOR, "Registered as MCO event listener");
}

void SensorControl_RunDiagnostics(void) {
	if (!sensor_ctrl.initialized) {
		return;
	}

	uint32_t now = HAL_GetTick();
	if (now - sensor_ctrl.last_diag_ms < 5000) {
		return; /* Throttle to every 5 seconds */
	}
	sensor_ctrl.last_diag_ms = now;

	/* Temperature diagnostics */
	int16_t temp = Temp_GetValue();
	uint8_t tq = Temp_GetSignalQuality();
	Temp_State_t ts = Temp_GetState();

	/* Electrode (mV) diagnostics */
	uint16_t mv = pH_GetMillivolts();
	uint8_t pq = pH_GetSignalQuality();
	pH_State_t ps = pH_GetState();

	/* StatusWord */
	uint16_t sw = sensor_ctrl.last_status_word;

	DBG_PRINT(SENSOR,
			"DIAG: state=%d SW=0x%04X | temp=%d.%d C q=%u%% s=%d | mV=%u q=%u%% s=%d",
			sensor_ctrl.current_state, sw, temp / 10,
			(temp >= 0 ? temp : -temp) % 10, tq, ts, mv, pq, ps);
}

SensorState_t SensorControl_GetState(void) {
	return sensor_ctrl.current_state;
}

/* Private functions ---------------------------------------------------------*/

/**
 * @brief  Generate CiA 404 StatusWord from current sensor states
 * @retval 16-bit StatusWord for process image (0x6041)
 */
static uint16_t SensorControl_GenerateStatusWord(void) {
	uint16_t sw = 0;

	/* Bit 0: pH sensor ready (active, not idle/error) */
	if (PH_IS_ACTIVE()) {
		sw |= SW_PH_READY;
	}

	/* Bit 1: Temperature sensor ready (active, not idle/error) */
	if (TEMP_IS_ACTIVE()) {
		sw |= SW_TEMP_READY;
	}

	/* Bit 3: General fault */
	if (sensor_ctrl.current_state == SENSOR_STATE_FAULT) {
		sw |= SW_FAULT;
	}

	/* Bit 4: pH sensor fault */
	if (sensor_ctrl.ph_initialized && pH_GetState() == PH_STATE_ERROR) {
		sw |= SW_PH_FAULT;
	}

	/* Bit 5: Temperature sensor fault */
	if (sensor_ctrl.temp_initialized && Temp_GetState() == TEMP_STATE_ERROR) {
		sw |= SW_TEMP_FAULT;
	}

	/* Bit 6: Warming up */
	if (sensor_ctrl.current_state == SENSOR_STATE_WARMING_UP) {
		sw |= SW_WARMING_UP;
	}

	/* Bit 9: Remote (NMT Operational) */
	if (MY_NMT_STATE == NMTSTATE_OP) {
		sw |= SW_REMOTE;
	}

	return sw;
}

/**
 * @brief  Process ControlWord with rising-edge detection
 * @param  control_word  Current ControlWord read from process image (0x6040)
 * @note   Detects rising edges (0→1 transitions) and dispatches:
 *         - Bit 7: Fault reset → clear errors, state → DISABLED
 *         (Calibration ControlWord bits are gone — the MIK owns calibration.)
 */
static void SensorControl_ProcessControlWord(uint16_t control_word) {
	/* Detect rising edges */
	uint16_t rising = control_word & ~sensor_ctrl.last_control_word;
	sensor_ctrl.last_control_word = control_word;

	if (rising == 0) {
		return; /* No new edges */
	}

	/* Fault reset (bit 7) */
	if (rising & CW_FAULT_RESET) {
		DBG_STATE(SENSOR, "ControlWord: FAULT_RESET");
		sensor_ctrl.current_state = SENSOR_STATE_DISABLED;

		/* Clear sensor errors */
		if (sensor_ctrl.temp_initialized) {
			Temp_ClearError();
		}
		if (sensor_ctrl.ph_initialized) {
			pH_ClearError();
		}
	}
}

/**
 * @brief  Check delta thresholds and trigger TPDOs if exceeded
 * @note   Compares current mV/temp/status against last TPDO'd values.
 *         TPDO1 (0x184): pHMillivolts + Temperature (measurement data)
 *         TPDO2 (0x284): SensorStatus + Quality + Error + StatusWord
 */
static void SensorControl_CheckDeltaTrigger(void) {
	bool trigger_tpdo1 = false;
	bool trigger_tpdo2 = false;

	/* ── TPDO1: electrode mV + Temperature delta check ────────────── */
	uint16_t cur_mv = pH_GetMillivolts();
	int16_t cur_temp = Temp_GetValue();

	uint16_t mv_threshold = ProcImg_GetMillivoltDeltaThreshold();
	int16_t temp_threshold = ProcImg_GetTempDeltaThreshold();

	/* mV delta (unsigned comparison) */
	if (mv_threshold > 0) {
		uint16_t mv_diff;
		if (cur_mv >= sensor_ctrl.last_tpdo_mv) {
			mv_diff = cur_mv - sensor_ctrl.last_tpdo_mv;
		} else {
			mv_diff = sensor_ctrl.last_tpdo_mv - cur_mv;
		}
		if (mv_diff >= mv_threshold) {
			trigger_tpdo1 = true;
		}
	}

	/* Temperature delta (signed, compare absolute difference) */
	if (temp_threshold > 0) {
		int16_t temp_diff = cur_temp - sensor_ctrl.last_tpdo_temp;
		if (temp_diff < 0)
			temp_diff = -temp_diff;
		if (temp_diff >= temp_threshold) {
			trigger_tpdo1 = true;
		}
	}

	if (trigger_tpdo1) {
		MCO_TriggerTPDO(1); /* TPDO1 (1-indexed per MCO API) */
		sensor_ctrl.last_tpdo_mv = cur_mv;
		sensor_ctrl.last_tpdo_temp = cur_temp;
		DBG_PRINT_V(SENSOR, "TPDO1 delta trigger: mV=%u temp=%d", cur_mv,
				cur_temp);
	}

	/* ── TPDO2: SensorStatus + StatusWord delta check ─────────────── */
	uint8_t status_threshold = ProcImg_GetStatusDeltaThreshold();
	uint16_t cur_sw = sensor_ctrl.last_status_word;

	/* Build SensorStatus bitfield for comparison (must match UpdateProcessImage) */
	uint8_t cur_status = 0;
	if (PH_IS_ACTIVE()) {
		cur_status |= 0x01; /* bit 0: electrode OK */
	}
	if (TEMP_IS_ACTIVE()) {
		cur_status |= 0x02; /* bit 1: temp OK */
	}
	if (sensor_ctrl.current_state == SENSOR_STATE_FAULT) {
		cur_status |= 0x08; /* bit 3: fault */
	}

	/* Check status byte change */
	if (status_threshold > 0) {
		uint8_t status_diff;
		if (cur_status >= sensor_ctrl.last_tpdo_status) {
			status_diff = cur_status - sensor_ctrl.last_tpdo_status;
		} else {
			status_diff = sensor_ctrl.last_tpdo_status - cur_status;
		}
		if (status_diff >= status_threshold) {
			trigger_tpdo2 = true;
		}
	}

	/* Also trigger TPDO2 if StatusWord changed (any bit flip).
	 * Note: last_status_word reflects the value from the previous cycle's
	 * UpdateProcessImage(), so cur_sw here is still the old value.
	 * We compare current computed status against what was last TPDO'd. */
	if (cur_status != sensor_ctrl.last_tpdo_status) {
		trigger_tpdo2 = true;
	}

	if (trigger_tpdo2) {
		MCO_TriggerTPDO(2); /* TPDO2 (1-indexed per MCO API) */
		sensor_ctrl.last_tpdo_status = cur_status;
		DBG_PRINT_V(SENSOR, "TPDO2 delta trigger: status=0x%02X SW=0x%04X",
				cur_status, cur_sw);
	}
}

/**
 * @brief  Write current sensor readings + status into MCO process image
 * @note   Called every SensorControl_Process() iteration.
 *         The MCO stack serves these values to SDO reads and TPDO mappings.
 */
static void SensorControl_UpdateProcessImage(void) {
	/* ── Temperature objects ──────────────────────────────────── */
	ProcImg_SetTemperature(Temp_GetValue());
	ProcImg_SetTempSensorStatus((uint8_t) Temp_GetState());

	/* Temp quality: only update process image if change > hysteresis */
	{
		uint8_t tq = Temp_GetSignalQuality();
		uint8_t diff =
				(tq >= sensor_ctrl.pimg_temp_quality) ?
						(tq - sensor_ctrl.pimg_temp_quality) :
						(sensor_ctrl.pimg_temp_quality - tq);
		if (diff >= QUALITY_HYSTERESIS) {
			sensor_ctrl.pimg_temp_quality = tq;
			ProcImg_SetTempSignalQuality(tq);
		}
	}

	/* ── Electrode (mV) objects ───────────────────────────────── */
	ProcImg_SetpHMillivolts(pH_GetMillivolts());
	ProcImg_SetpHSensorStatus((uint8_t) pH_GetState());

	/* pH quality: only update process image if change > hysteresis */
	{
		uint8_t pq = pH_GetSignalQuality();
		uint8_t diff =
				(pq >= sensor_ctrl.pimg_ph_quality) ?
						(pq - sensor_ctrl.pimg_ph_quality) :
						(sensor_ctrl.pimg_ph_quality - pq);
		if (diff >= QUALITY_HYSTERESIS) {
			sensor_ctrl.pimg_ph_quality = pq;
			ProcImg_SetpHSignalQuality(pq);
		}
	}

	/* ── StatusWord (0x6041) ──────────────────────────────────── */
	uint16_t sw = SensorControl_GenerateStatusWord();
	ProcImg_SetStatusWord(sw);
	sensor_ctrl.last_status_word = sw;

	/* ── SensorStatus bitfield (0x2300) ──────────────────────── */
	uint8_t sensor_status = 0;
	if (PH_IS_ACTIVE()) {
		sensor_status |= 0x01; /* bit 0: electrode OK */
	}
	if (TEMP_IS_ACTIVE()) {
		sensor_status |= 0x02; /* bit 1: temp OK */
	}
	if (sensor_ctrl.current_state == SENSOR_STATE_FAULT) {
		sensor_status |= 0x08; /* bit 3: fault */
	}
	ProcImg_SetSensorStatus(sensor_status);

	/* ── ErrorRegister (0x1001) ──────────────────────────────── */
	uint8_t err_reg = 0;
	if (sensor_ctrl.current_state == SENSOR_STATE_FAULT) {
		err_reg |= 0x01; /* generic error */
	}
	if ((sensor_ctrl.ph_initialized && pH_GetState() == PH_STATE_ERROR)
			|| (sensor_ctrl.temp_initialized
					&& Temp_GetState() == TEMP_STATE_ERROR)) {
		err_reg |= 0x20; /* device-specific error */
	}
	ProcImg_SetErrorRegister(err_reg);
}

/**
 * @brief Handle MCO events (same pattern as pump's MotorControl)
 */
static void SensorControl_HandleMCOEvent(const MCO_Event_t *event) {
	switch (event->type) {
	case MCO_EVENT_FATAL_ERROR:
		DBG_ERROR(SENSOR, "MCO fatal error: code=%u", event->error_code);
		SensorControl_EmergencyStop();
		break;

	case MCO_EVENT_COMM_RESET:
		if (event->init_result) {
			DBG_PRINT(SENSOR,
					"COMM_RESET: stack init OK, initializing sensors");
			if (!SensorControl_Init()) {
				DBG_ERROR(SENSOR, "SensorControl_Init failed");
			}
		} else {
			DBG_ERROR(SENSOR, "COMM_RESET: stack init FAILED");
		}
		break;

	case MCO_EVENT_NMT_CHANGE:
		DBG_STATE(SENSOR, "NMT change: state=0x%02X", event->nmt_state);
		/* NMT gate in Process() handles state transitions.
		 * No explicit Reset here — avoids clearing state prematurely
		 * when the NMT gate will handle it next cycle. */
		break;

	case MCO_EVENT_HEARTBEAT_LOST:
		DBG_ERROR(SENSOR, "Heartbeat lost: node=%u", event->node_id);
		SensorControl_EmergencyStop();
		break;
	}
}
